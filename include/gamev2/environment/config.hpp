/// @file config.hpp
/// @brief 环境模块的调平衡旋钮，随配置加载一次。
///
/// 不做成编译期常量，与 GeneticsConfig 同一个理由：这些恰恰是需要反复调整的
/// 参数，固化进二进制会让每次调参都变成一次重编。
#pragma once

#include <cstddef>
#include <cstdint>

namespace gamev2::environment {

struct EnvironmentConfig
{
    /// \pre steps_per_season >= 1：run_season 用它做归一化除数，0 会让
    ///      feeding 变成 NaN。本模块没有配置期校验机制，因此这里只写明，
    ///      不在运行时拦。
    std::uint32_t steps_per_season = 8;
    /// fertility = 1 时一格支持几个体，即**出生硬上限**：任何一季的出生数加上
    /// 在场数都不得超过 Σcapacity = 4096 × capacity_base × mean(base_fertility)，
    /// 而 mean(base_fertility) = (0.25 + 1) / 2 = 0.625 —— 不是 1。
    ///
    /// 它**不是**种群平衡点。满占用下每步需求是 demand_rate × d × n = 0.35c，
    /// 而再生上限只有 regen_rate × c = 0.25c（d = 1），满占用本来就不可持续；
    /// 实测 N = 9984 时 feeding 已是 mean 0.796 / min 0.321 且仍在下降。
    /// 未饱和分支的均衡解约为 n ≈ c / (1.75 d) ≈ 0.57c，远在上限之下。
    ///
    /// 真要把稳定种群顶到 1 万，要调的是 regen_rate / demand_rate 而不是
    /// capacity_base；确切均衡点还需要遗传层的存活率才解得出来，本内核给不出。
    float capacity_base = 3.9f;
    /// 地形中水格应占的比例。海平面取**全图高程的这个百分位**而不是写死
    /// 一个常数：写死的话不同种子的水陆比会在 15%~50% 之间乱跳，这个值就
    /// 成了一个平均数而不是保证值。
    ///
    /// 0 表示全陆地（既有 environment 测试靠这个配置保持原有断言），
    /// 1 表示除最高一格外全水。
    ///
    /// \pre 取值 ∈ [0, 1]：它直接当分位数下标用，越界会索引出 std::array。
    /// 默认 0.70 而不是凭直觉的「三成水」：陆地是否碎成多块由海平面落在
    /// 高程分布的哪个位置决定，而海平面取的是这个百分位。实测（见
    /// doc/2026-10-17-game-design.md §4.1 的六种子实测表与 terrain.cpp
    /// 的基频注释）在
    /// 0.35 下六个种子有三个给出 2640 格的单一大陆，阶段 2 的屏障无从
    /// 成立；0.70 下每个种子都有一块 226~474 格的次大陆。
    float water_fraction = 0.70f;
    /// 个体每季跟资源存量梯度的概率，其余走随机游走。
    ///
    /// 0.5 让趋向与随机游走势均力敌，个体既不会全挤向富格、也不会完全
    /// 失去方向感；再高则同格的个体会高度同步（它们看到的邻域完全相同），
    /// 全军爬上同一个局部极大。0 表示关闭趋向，退回纯随机游走——集成测试
    /// 的对照组正是它。
    ///
    /// **不要用「定向行程够长就能跜到对岸」来论证屏障。** 那条推理错在方向：
    /// 梯度步永远落在可通行邻格上，跨屏需要一条路径，而屏障没有缝。屏障是
    /// **绝对的**，靠 4 邻域移动逐格判通行那条不变量成立，与走多远无关。
    /// 设计文档 §4.1 那一段的同类表述已一并更正。
    ///
    /// \pre 取值 ∈ [0, 1]。本模块没有配置期校验机制，只在这里写明。
    float gradient_weight = 0.5f;
    /// 初始种群共同的创始基因型个数。整个世界从这一小撮起步，而不是每个个体
    /// 各拿一份独立随机基因型 —— 后者让第 0 季的 divergence 就达 1.75
    /// （值域 [0, 150]），真分化与初始抽样噪声分不开，任何 θ 都修不了。
    ///
    /// 取 32 使全图 ≈ 2400 个个体承受一次强瓶颈，之后分化只因屏障两侧无法
    /// 基因交流而累积。实测见 doc/2026-10-17-game-design.md §2.3。
    ///
    /// \pre >= 1：0 会让 founders 容器为空，播种时索引越界。
    std::uint32_t seed_founder_pool = 32;
    /// 每个个体在自己那份创始基因型上，按此概率把某个位点的两个等位基因
    /// 重新掷一遍。32 × 0.001 × 300 ≈ 每个个体约 0.3 个位点被重掷——足够
    /// 让同源个体之间有一点点私有差异，不足以让它们变成互不相关的谱系。
    float seed_mutation_rate = 0.001f;
    /// 分裂出去的群体至少要有这么多个体。**Species 被玩家批评得最狠的一条**：
    /// 新物种只有 1 个个体样本，无法繁殖或繁殖困难而灭绝。
    ///
    /// 200 季实测各陆块 1225 / 517 / 161 / 104 / 72 / 71，因此 40 留下
    /// 6~9 块够格，`target_species = 3` 可达（设计文档 §2.3）。
    std::size_t min_founder = 40;
    /// 组对全体的 divergence 门槛。**它的值域是 [0, 位点数/2]（全激活时
    /// [0, 150]），不是 [0, 0.5]** —— 把它当归一化量读就是 θ 定错两个数量级
    /// 的来源。10.0 的实测依据见设计文档 §2.3。
    float divergence_threshold = 10.0f;
    /// 连续满足前几条条件的季数。挡的是「群体规模在阈值上下抖时抖出一棵
    /// 全是死枝的进化树」。
    std::uint32_t speciation_hysteresis = 4;
    /// 迟滞锚点的跨季匹配半径，单位为格。上一季的锚与本季某分量的锚距离
    /// 不超过它，则该分量继承上一季的连续季数。
    ///
    /// 取 8 的依据：单季位移 1~2 格（max(1, lround(clamp(Speed,0,3))))，
    /// 200 季的漂移 σ ≈ 15 格。8 格既不会被一步移动甩掉，也不会把相邻的
    /// 两个小陆块错认成同一个。
    ///
    /// \pre >= 0：0 表示只有锚完全重合才算同一分量。
    float hysteresis_radius_cells = 8.0f;
    /// 每步向 capacity 回归的比例，(0, 1]。
    float regen_rate = 0.25f;
    /// 单体单步的绝对摄取上限，与 share 同量纲（都是「个体」）：want 取它乘
    /// 表型需求，人均可得不足 want 时才按 share 截断。它是绝对量而非存量比例，
    /// 否则会被 got = min(want, share) 约掉，feeding 对存量退化为常数。
    float demand_rate = 0.35f;
    /// 每个体本季最多产几个子代。
    /// \pre offspring_scale >= 0：build_sites 把它折成
    ///      `static_cast<std::uint32_t>(lround(here * offspring_scale))`，
    ///      负值转无符号是 UB（不是饱和转换）。本模块没有配置期校验机制，
    ///      因此这里只写明，不在运行时拦。
    float offspring_scale = 2.0f;
    /// 局部交配半径，单位为格。0 表示只有本格内个体互相交配。
    float mating_radius_cells = 1.0f;
    float temperature_amplitude = 6.0f;
    float temperature_period = 8.0f;  ///< 季节数 / 周期
    float light_amplitude = 0.15f;
};

}  // namespace gamev2::environment
